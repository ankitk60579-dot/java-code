
public class Student {
	int id;
	String name;
	float fine;
	public Student(int id, String name,float fine) {
		super();
		this.id=id;
		this.name=name;
		this.fine=fine;
		
	}
	public int getId() {
		return id;
	}
public String getname() {
	return name;
	
}
public float getfine() {
	return fine;
}
}
